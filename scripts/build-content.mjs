// Generates util/generated-posts.ts from content/posts/*.mdx frontmatter.
//
// Replaces contentlayer (whose CLI is broken on modern Node and whose
// useMDXComponent evals via new Function(), forbidden on Cloudflare Workers).
// MDX bodies are precompiled separately by scripts/compile-mdx.mjs.
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const matter = require('gray-matter')

const root = new URL('../', import.meta.url).pathname
const contentDir = join(root, 'content', 'posts')

const files = (await readdir(contentDir)).filter((f) => f.endsWith('.mdx'))

const posts = []
for (const file of files) {
  const raw = await readFile(join(contentDir, file), 'utf8')
  const { data, content } = matter(raw)
  if (!data.title || !data.date || !data.hero || !data.tags) {
    throw new Error(`${file}: missing required frontmatter (title/date/hero/tags)`)
  }
  const flattenedPath = join('posts', file.replace(/\.mdx$/, '')).split(sep).join('/')
  const slug = flattenedPath.split('/').slice(1).join('/')
  const words = content.split(/\s+/).filter(Boolean).length
  posts.push({
    published: data.published ?? false,
    title: data.title,
    description: data.description ?? '',
    date: new Date(data.date).toISOString(),
    ...(data.updated ? { updated: new Date(data.updated).toISOString() } : {}),
    ...(data.url ? { url: data.url } : {}),
    hero: data.hero,
    tags: data.tags,
    ...(data.heroSource ? { heroSource: data.heroSource } : {}),
    path: `/${flattenedPath}`,
    slug,
    readTime: Math.ceil(words / 200),
    body: { raw: content },
  })
}

// Newest first.
posts.sort((a, b) => (new Date(a.date) > new Date(b.date) ? -1 : 1))

const out = `// GENERATED by scripts/build-content.mjs — do not edit.
export type Post = {
  published: boolean
  title: string
  description: string
  date: string
  updated?: string
  url?: string
  hero: string
  tags: string[]
  heroSource?: string
  path: string
  slug: string
  readTime: number
  body: { raw: string }
}

export const allPosts: Post[] = ${JSON.stringify(posts, null, 2)}
`

await writeFile(join(root, 'util', 'generated-posts.ts'), out)
console.log(`wrote util/generated-posts.ts with ${posts.length} posts`)
